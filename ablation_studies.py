import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split, RandomizedSearchCV
from sklearn.ensemble import GradientBoostingClassifier, VotingClassifier
from sklearn.naive_bayes import GaussianNB
from sklearn.metrics import accuracy_score, precision_score, recall_score, confusion_matrix
from sklearn.preprocessing import StandardScaler
from scipy.stats import randint, uniform
from collections import defaultdict

# Load dataset
df = pd.read_csv('/content/Vibration_Dataset.csv')

# Define number of last columns used as targets (assuming last 8 columns are fault types)
num_targets = 8
X = df.iloc[:, :-num_targets]  # Features
target_columns = df.columns[-num_targets:]  # Last 8 columns as target names

results = defaultdict(dict)

for target in target_columns:
    print(f"Training for fault: {target}")

    y = df[target]

    # Handle missing values if any
    X_filled = X.fillna(X.mean())

    # Scaling
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X_filled)

    # Train-test split (fixed random_state for reproducibility)
    X_train, X_test, y_train, y_test = train_test_split(
        X_scaled, y, test_size=0.3, stratify=y, random_state=42
    )

    # Hyperparameter distribution for GBDT
    param_dist = {
        'n_estimators': randint(100, 500),
        'learning_rate': uniform(0.01, 0.2),
        'max_depth': randint(3, 10),
        'min_samples_split': randint(2, 10),
        'min_samples_leaf': randint(1, 10),
        'subsample': uniform(0.6, 0.4)
    }

    gbdt = GradientBoostingClassifier(random_state=42)

    # Randomized search for GBDT++
    random_search = RandomizedSearchCV(
        gbdt, param_distributions=param_dist,
        n_iter=30, cv=3, scoring='accuracy',
        random_state=42, n_jobs=-1, verbose=1
    )

    # Fit randomized search
    random_search.fit(X_train, y_train)
    best_gbdt = random_search.best_estimator_

    # Gaussian Naive Bayes
    gnb = GaussianNB()

    # Voting Classifier (GBDT++ + GNB)
    voting_clf = VotingClassifier(
        estimators=[('gbdt', best_gbdt), ('gnb', gnb)],
        voting='hard'
    )

    # Train the hybrid model
    voting_clf.fit(X_train, y_train)

    # Predict on test set
    y_pred = voting_clf.predict(X_test)

    # Calculate metrics
    acc = accuracy_score(y_test, y_pred)
    prec = precision_score(y_test, y_pred, zero_division=0)
    rec = recall_score(y_test, y_pred, zero_division=0)
    tn, fp, fn, tp = confusion_matrix(y_test, y_pred).ravel()
    specificity = tn / (tn + fp) if (tn + fp) > 0 else 0

    # Store results
    results[target]['accuracy'] = acc
    results[target]['precision'] = prec
    results[target]['recall'] = rec
