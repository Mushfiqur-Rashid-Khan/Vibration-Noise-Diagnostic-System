import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from imblearn.over_sampling import SMOTE
from sklearn.metrics import accuracy_score, precision_score, recall_score, confusion_matrix, classification_report
import tensorflow as tf
import tensorflow_decision_forests as tfdf
import matplotlib.pyplot as plt
import seaborn as sns
from collections import defaultdict

# 1. Load dataset
df = pd.read_csv('/content/Vibration_Dataset.csv')

# 2. Define features and targets (last 8 columns assumed faults)
num_targets = 8
X = df.iloc[:, :-num_targets]  # Features
target_columns = df.columns[-num_targets:]  # Last 8 columns

# Store results for each fault type
results = defaultdict(dict)

for target in target_columns:
    print(f"\nTraining for fault: {target}")

    y = df[target]

    # 3. Train-test split with stratification
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.3, stratify=y, random_state=42
    )

    # 4. Scaling features
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled = scaler.transform(X_test)

    # 5. SMOTE to balance classes in training data
    smote = SMOTE(random_state=42)
    X_res, y_res = smote.fit_resample(X_train_scaled, y_train)

    # 6. PCA for dimensionality reduction (retain 95% variance)
    pca = PCA(n_components=0.95, random_state=42)
    X_train_pca = pca.fit_transform(X_res)
    X_test_pca = pca.transform(X_test_scaled)

    # 7. Prepare DataFrame for TFDF - convert labels to strings for classification
    train_df = pd.DataFrame(X_train_pca)
    train_df['label'] = y_res.astype(str).values  # Convert labels to string

    test_df = pd.DataFrame(X_test_pca)
    test_df['label'] = y_test.astype(str).values  # Convert labels to string

    # 8. Convert pandas DataFrame to TensorFlow dataset
    train_ds = tfdf.keras.pd_dataframe_to_tf_dataset(train_df, label='label')
    test_ds = tfdf.keras.pd_dataframe_to_tf_dataset(test_df, label='label')

    # 9. Initialize and train TFDF Gradient Boosted Trees model
    model = tfdf.keras.GradientBoostedTreesModel(verbose=0)
    model.fit(train_ds)

    # 10. Predict on test set
    predictions = model.predict(test_ds)

    # TFDF returns predictions as a numpy array of shape (num_samples, num_classes)
    # Get predicted class index (argmax) for multiclass or binary classification
    if predictions.shape[1] > 1:
        y_pred_indices = np.argmax(predictions, axis=1)
        # Map indices back to label strings from the model
        class_labels = model.classes_
        y_pred = [class_labels[i] for i in y_pred_indices]
    else:
        # For binary classification, predictions shape might be (num_samples, 1)
        y_pred = (predictions.flatten() > 0.5).astype(int).astype(str)

    # 11. Convert true labels to string for consistency
    y_test_str = y_test.astype(str).values

    # 12. Calculate evaluation metrics
    acc = accuracy_score(y_test_str, y_pred)
    prec = precision_score(y_test_str, y_pred, pos_label='1', zero_division=0)
    rec = recall_score(y_test_str, y_pred, pos_label='1', zero_division=0)

    # Confusion matrix for binary classification (assuming labels '0' and '1')
    cm = confusion_matrix(y_test_str, y_pred, labels=['0', '1'])
    tn, fp, fn, tp = cm.ravel() if cm.size == 4 else (0,0,0,0)
    specificity = tn / (tn + fp) if (tn + fp) > 0 else 0

    # Save results
    results[target]['accuracy'] = acc
    results[target]['precision'] = prec
    results[target]['recall'] = rec
    results[target]['specificity'] = specificity

    # 13. Print classification report
    print(f"Accuracy: {acc:.3f}")
    print(f"Precision: {prec:.3f}")
    print(f"Recall: {rec:.3f}")
    print(f"Specificity: {specificity:.3f}")
    print("Classification Report:\n", classification_report(y_test_str, y_pred, zero_division=0))

    # 14. Plot confusion matrix
    plt.figure(figsize=(5, 4))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=['No Fault', 'Fault'], yticklabels=['No Fault', 'Fault'])
    plt.title(f'Confusion Matrix for {target}')
    plt.xlabel('Predicted')
    plt.ylabel('Actual')
    plt.tight_layout()
    plt.show()

