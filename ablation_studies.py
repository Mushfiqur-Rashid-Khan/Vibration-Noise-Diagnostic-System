import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.ensemble import GradientBoostingClassifier, ExtraTreesClassifier
from sklearn.metrics import accuracy_score, precision_score, recall_score, confusion_matrix
from sklearn.preprocessing import StandardScaler
from collections import defaultdict
import tensorflow_decision_forests as tfdf
import tensorflow as tf

# Load dataset
df = pd.read_csv('/content/Vibration_Dataset.csv')

# Define number of last columns used as targets
num_targets = 8
X = df.iloc[:, :-num_targets]  # Features
target_columns = df.columns[-num_targets:]  # Last 8 columns as target names

results = defaultdict(dict)

for target in target_columns:
    print(f"\nTraining for fault: {target}")
    y = df[target]

    # Handle missing values
    X_filled = X.fillna(X.mean())

    # Scaling
    scaler = StandardScaler()
    X_scaled = scaler.fit_transform(X_filled)

    # Train-test split
    X_train, X_test, y_train, y_test = train_test_split(
        X_scaled, y, test_size=0.3, stratify=y, random_state=42
    )

    # 1. Extra Trees
    et_model = ExtraTreesClassifier(n_estimators=100, random_state=42)
    et_model.fit(X_train, y_train)
    et_preds = et_model.predict(X_test)

    # 2. Gradient Boosting
    gb_model = GradientBoostingClassifier(n_estimators=100, random_state=42)
    gb_model.fit(X_train, y_train)
    gb_preds = gb_model.predict(X_test)

    # 3. TFDF Model (Gradient Boosted Trees)
    # Convert to DataFrame for TFDF
    X_train_df = pd.DataFrame(X_train, columns=[f'F{i}' for i in range(X_train.shape[1])])
    X_train_df['label'] = y_train.values

    X_test_df = pd.DataFrame(X_test, columns=[f'F{i}' for i in range(X_test.shape[1])])
    X_test_df['label'] = y_test.values

    train_ds = tfdf.keras.pd_dataframe_to_tf_dataset(X_train_df, label="label")
    test_ds = tfdf.keras.pd_dataframe_to_tf_dataset(X_test_df, label="label")

    tf_model = tfdf.keras.GradientBoostedTreesModel()
    tf_model.fit(train_ds, verbose=0)

    tf_preds_prob = tf_model.predict(test_ds)
    tf_preds = np.argmax(tf_preds_prob, axis=1)  # Binary: assumes labels [0,1]

    # 4. Voting: Majority vote (binary case)
    # Ensure all predictions are integer numpy arrays
    ensemble_preds = ((et_preds + gb_preds + tf_preds) > 1).astype(int)

    # 5. Evaluation
    acc = accuracy_score(y_test, ensemble_preds)
    prec = precision_score(y_test, ensemble_preds, zero_division=0)
    rec = recall_score(y_test, ensemble_preds, zero_division=0)
    tn, fp, fn, tp = confusion_matrix(y_test, ensemble_preds).ravel()
    specificity = tn / (tn + fp) if (tn + fp) > 0 else 0

    # Store results
    results[target]['accuracy'] = acc
    results[target]['precision'] = prec
    results[target]['recall'] = rec
    results[target]['specificity'] = specificity

# Convert to DataFrame
results_df = pd.DataFrame(results).T.reset_index()
results_df.rename(columns={'index': 'Fault_Type'}, inplace=True)

print("\nSummary of TFXGBT Results (without SMOTE):")
print(results_df.round(3))

