"""**Cost-Sensitive LightGBM**"""

import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from imblearn.over_sampling import SMOTE
from sklearn.decomposition import PCA
from lightgbm import LGBMClassifier
from sklearn.metrics import accuracy_score, precision_score, recall_score, confusion_matrix
from collections import defaultdict, Counter

# 1. Load the dataset
df = pd.read_csv('/content/Vibration_Dataset.csv')

# 2. Separate features and targets (last 8 columns as faults)
num_targets = 8
X = df.iloc[:, :-num_targets]
target_columns = df.columns[-num_targets:]

# 3. Dictionary to hold results
results = defaultdict(dict)

# 4. Loop through each fault type
for target in target_columns:
    y = df[target]

    # Train-test split
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.3, stratify=y, random_state=42
    )

    # Scaling
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_test_scaled = scaler.transform(X_test)

    # Apply SMOTE
    smote = SMOTE(random_state=42)
    X_res, y_res = smote.fit_resample(X_train_scaled, y_train)

    # PCA
    pca = PCA(n_components=0.95, random_state=42)
    X_train_pca = pca.fit_transform(X_res)
    X_test_pca = pca.transform(X_test_scaled)

    # Class weights for cost-sensitive learning
    class_counts = Counter(y_res)
    total = sum(class_counts.values())
    class_weights = {cls: total / (len(class_counts) * count) for cls, count in class_counts.items()}
    sample_weights = np.array([class_weights[label] for label in y_res])

    # Train Cost-Sensitive LightGBM
    lgb_model = LGBMClassifier(random_state=42)
    lgb_model.fit(X_train_pca, y_res, sample_weight=sample_weights)

    # Prediction
    y_pred = lgb_model.predict(X_test_pca)

    # Metrics
    acc = accuracy_score(y_test, y_pred)
    prec = precision_score(y_test, y_pred)
    rec = recall_score(y_test, y_pred)

    tn, fp, fn, tp = confusion_matrix(y_test, y_pred).ravel()
    specificity = tn / (tn + fp)

    # Store results
    results[target]['accuracy_with_cost_lgbm'] = acc
    results[target]['precision_with_cost_lgbm'] = prec
    results[target]['recall_with_cost_lgbm'] = rec
    results[target]['specificity_with_cost_lgbm'] = specificity

# Compile results into DataFrame
results_df = pd.DataFrame(results).T.reset_index()
results_df.rename(columns={'index': 'Fault_Type'}, inplace=True)

# Display formatted results
print(results_df.round(3))

