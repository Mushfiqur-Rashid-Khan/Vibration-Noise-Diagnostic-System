class RMEL(BaseEstimator, ClassifierMixin):
    """
    Robust Model Ensemble Layer
    """
    def __init__(self, base_estimator=None, n_estimators=10):
        self.base_estimator = base_estimator
        self.n_estimators = n_estimators
        self.estimators_ = []

    def fit(self, X, y):
        # Initialize ensemble
        self.estimators_ = []

        # Create and train ensemble members
        for i in range(self.n_estimators):
            # Use different random seeds for diversity
            if self.base_estimator is not None:
                estimator = self.base_estimator(random_state=i)
            else:
                # Default to a simple model if none provided
                from sklearn.ensemble import RandomForestClassifier
                estimator = RandomForestClassifier(n_estimators=10, random_state=i)

            # Bootstrap sample
            n_samples = X.shape[0]
            indices = np.random.choice(n_samples, n_samples, replace=True)
            X_boot = X[indices]
            y_boot = y[indices]

            # Train
            estimator.fit(X_boot, y_boot)
            self.estimators_.append(estimator)

        return self

    def predict(self, X):
        # Get predictions from all estimators
        predictions = np.array([estimator.predict(X) for estimator in self.estimators_])

        # Majority voting
        from scipy.stats import mode
        final_predictions = mode(predictions, axis=0)[0].flatten()

        return final_predictions

    def predict_proba(self, X):
        # Average probabilities from all estimators
        probas = np.array([estimator.predict_proba(X) for estimator in self.estimators_])
        return np.mean(probas, axis=0)

