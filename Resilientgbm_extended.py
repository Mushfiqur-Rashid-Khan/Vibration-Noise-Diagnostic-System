# RESIDUAL MEMORY EMBEDDING LAYER (RMEL)
# -----------------------------
class RMEL:
    def __init__(self, input_dim, hidden_dim=16):
        self.mlp = MLPRegressor(
            hidden_layer_sizes=(hidden_dim,),
            max_iter=100,
            random_state=42,
            early_stopping=True,
            validation_fraction=0.1,
            n_iter_no_change=10,
            verbose=False
        )
        self.fitted = False

    def fit(self, X, residuals):
        self.mlp.fit(X, residuals)
        self.fitted = True
        return self.transform(X, residuals)

    def transform(self, X, residuals=None):
        if not self.fitted:
            raise ValueError("RMEL must be fitted before transform")

        emb = self.mlp.predict(X).reshape(-1, 1)

        if residuals is not None:
            Z = X + 0.1 * emb + 0.01 * residuals.reshape(-1, 1)
        else:
            Z = X + 0.1 * emb

        return Z

# -----------------------------
# RESILIENT GBM FOR MULTI-LABEL
# -----------------------------
class ResilientGBMMultiLabel:
    def __init__(self, n_estimators=100, learning_rate=0.1, max_depth=5,
                 num_leaves=31, min_child_samples=20, subsample=0.8,
                 colsample_bytree=0.8, random_state=42):
        self.n_estimators = n_estimators
        self.learning_rate = learning_rate
        self.max_depth = max_depth
        self.num_leaves = num_leaves
        self.min_child_samples = min_child_samples
        self.subsample = subsample
        self.colsample_bytree = colsample_bytree
        self.random_state = random_state
        self.models = {}
        self.rm_layer = None
        self.fitted = False
        self.feature_importance = None
        self.target_names = None

    def fit(self, X, Y, target_names=None):
        self.target_names = target_names

        # Initialize residuals
        residuals = np.zeros(X.shape[0])

        # Create and fit RMEL
        self.rm_layer = RMEL(input_dim=X.shape[1])
        X_emb = self.rm_layer.fit(X, residuals)

        # Train one model per target
        print(f"\n{'='*70}")
        print("TRAINING INDIVIDUAL FAULT DETECTION MODELS")
        print("="*70)

        for i in range(Y.shape[1]):
            y_i = Y[:, i]
            fault_name = target_names[i] if target_names else f"Fault_{i+1}"

            # Skip if all same
            if len(np.unique(y_i)) == 1:
                print(f"\n{i+1}. {fault_name}: SKIPPED (only one class)")
                continue

            # Calculate class distribution
            pos_count = np.sum(y_i)
            neg_count = len(y_i) - pos_count

            print(f"\n{i+1}. {fault_name}:")
            print(f"   Positive: {pos_count:4d} ({pos_count/len(y_i)*100:.1f}%)")
            print(f"   Negative: {neg_count:4d} ({neg_count/len(y_i)*100:.1f}%)")
            print(f"   Training...", end=" ")

            # Handle class imbalance with balanced weights
            model = lgb.LGBMClassifier(
                n_estimators=self.n_estimators,
                learning_rate=self.learning_rate,
                max_depth=self.max_depth,
                num_leaves=self.num_leaves,
                min_child_samples=self.min_child_samples,
                subsample=self.subsample,
                colsample_bytree=self.colsample_bytree,
                random_state=self.random_state,
                verbose=-1,
                class_weight='balanced',
                reg_alpha=0.1,
                reg_lambda=0.1,
                min_split_gain=0.01
            )

            # Train
            model.fit(X_emb, y_i)
            self.models[i] = model
            print("Done")

        self.fitted = True
        self._compute_feature_importance()
        print(f"\nTraining complete! {len(self.models)} models trained.")
        return self

    def _compute_feature_importance(self):
        """Compute average feature importance across all models"""
        if not self.models:
            return

        importance_list = []
        for model in self.models.values():
            if hasattr(model, 'feature_importances_'):
                importance_list.append(model.feature_importances_)

        if importance_list:
            self.feature_importance = np.mean(importance_list, axis=0)

    def predict(self, X):
        if not self.fitted:
            raise ValueError("Model must be fitted before prediction")

        X_emb = self.rm_layer.transform(X)

        predictions = []
        for i in sorted(self.models.keys()):
            y_pred = self.models[i].predict(X_emb)
            predictions.append(y_pred.reshape(-1, 1))

        return np.hstack(predictions)

    def predict_proba(self, X):
        if not self.fitted:
            raise ValueError("Model must be fitted before prediction")

        X_emb = self.rm_layer.transform(X)

        probabilities = []
        for i in sorted(self.models.keys()):
            y_proba = self.models[i].predict_proba(X_emb)
            # Get probability of positive class
            if y_proba.shape[1] == 2:
                proba = y_proba[:, 1].reshape(-1, 1)
            else:
                proba = y_proba[:, 0].reshape(-1, 1)
            probabilities.append(proba)

        return np.hstack(probabilities)

    def predict_single_fault(self, X, fault_idx):
        """Predict a single fault type"""
        if fault_idx not in self.models:
            raise ValueError(f"Fault {fault_idx} not found")

        X_emb = self.rm_layer.transform(X)
        return self.models[fault_idx].predict(X_emb)

    def predict_proba_single(self, X, fault_idx):
        """Predict probability for a single fault type"""
        if fault_idx not in self.models:
            raise ValueError(f"Fault {fault_idx} not found")

        X_emb = self.rm_layer.transform(X)
        proba = self.models[fault_idx].predict_proba(X_emb)
        return proba[:, 1] if proba.shape[1] == 2 else proba[:, 0]

    def get_shap_explainer(self, fault_idx):
        """Get SHAP explainer for a specific fault"""
        if fault_idx not in self.models:
            raise ValueError(f"Fault {fault_idx} not found")
        return shap.TreeExplainer(self.models[fault_idx])

    def explain_prediction(self, X, fault_idx):
        """Explain prediction for a specific fault"""
        if fault_idx not in self.models:
            raise ValueError(f"Fault {fault_idx} not found")

        X_emb = self.rm_layer.transform(X)
        model = self.models[fault_idx]

        explainer = shap.TreeExplainer(model)
        shap_values = explainer.shap_values(X_emb)

        return {
            'shap_values': shap_values,
            'base_value': explainer.expected_value,
            'model': model,
            'explainer': explainer
        }

