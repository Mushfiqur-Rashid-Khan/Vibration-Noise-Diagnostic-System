class RMEL:
    def __init__(self, input_dim, hidden_dim=16):
        self.mlp = MLPRegressor(
            hidden_layer_sizes=(hidden_dim,),
            max_iter=100,
            random_state=42,
            early_stopping=True,
            validation_fraction=0.1,
            n_iter_no_change=10
        )
        self.fitted = False

    def fit(self, X, residuals):
        self.mlp.fit(X, residuals)
        self.fitted = True
        return self.transform(X, residuals)

    def transform(self, X, residuals=None):
        if not self.fitted:
            raise ValueError("RMEL must be fitted before transform")

        emb = self.mlp.predict(X).reshape(-1, 1)

        if residuals is not None:
            Z = X + 0.1 * emb + 0.01 * residuals.reshape(-1, 1)
        else:
            Z = X + 0.1 * emb

        return Z

class ResilientGBMPlusPlus:
    def __init__(self, n_estimators=100, learning_rate=0.1, max_depth=4,
                 residual_memory=3, minority_class=1, early_stopping_rounds=20):
        self.n_estimators = n_estimators
        self.learning_rate = learning_rate
        self.max_depth = max_depth
        self.residual_memory = residual_memory
        self.minority_class = minority_class
        self.early_stopping_rounds = early_stopping_rounds
        self.model = None
        self.rm_layer = None
        self.X_emb = None
        self.fitted = False
        self.feature_importance = None

    # RGSS oversampling with controlled synthetic sample generation
    def rgss_oversample(self, X, y, residuals):
        idx = np.where(y == self.minority_class)[0]
        if len(idx) == 0:
            return X, y

        # Only oversample if minority class is less than 50% of majority
        majority_count = np.sum(y != self.minority_class)
        minority_count = len(idx)

        if minority_count > majority_count * 0.5:
            return X, y

        # Select top 30% samples with highest residuals
        n_top = max(1, int(0.3 * len(idx)))
        top_idx = idx[np.argsort(np.abs(residuals[idx]))[-n_top:]]

        # Generate synthetic samples (limited to avoid overfitting)
        n_synthetic = min(len(top_idx), max(1, int(majority_count * 0.2)))

        synth_samples = []
        synth_labels = []

        for _ in range(n_synthetic):
            i = np.random.choice(top_idx)
            j = np.random.choice(idx)
            lam = np.random.uniform(0.2, 0.8)  # Controlled interpolation
            x_new = X[i] + lam * (X[j] - X[i])
            # Add small noise for diversity
            noise = np.random.normal(0, 0.01, X.shape[1])
            x_new = x_new + noise
            synth_samples.append(x_new)
            synth_labels.append(self.minority_class)

        if len(synth_samples) > 0:
            X_aug = np.vstack([X, np.array(synth_samples)])
            y_aug = np.hstack([y, np.array(synth_labels)])
        else:
            X_aug, y_aug = X, y

        return X_aug, y_aug.astype(int)

    # Attention computation with smoothing
    def compute_attention(self, X):
        alpha = np.mean(np.abs(X), axis=1)
        alpha = alpha / (np.max(alpha) + 1e-8)
        # Add smoothing
        alpha = 0.5 + 0.5 * alpha
        return alpha

    # Fit method with cross-validation
    def fit(self, X, y):
        # Ensure y is integer
        y = y.astype(int)

        # Initialize residuals
        residuals = np.zeros(X.shape[0])

        # Create and fit RMEL
        self.rm_layer = RMEL(input_dim=X.shape[1])
        self.X_emb = self.rm_layer.fit(X, residuals)

        # Split for validation (20%)
        try:
            X_train_emb, X_val_emb, y_train_sub, y_val = train_test_split(
                self.X_emb, y, test_size=0.2, random_state=42, stratify=y
            )
        except ValueError:
            X_train_emb, X_val_emb, y_train_sub, y_val = train_test_split(
                self.X_emb, y, test_size=0.2, random_state=42, shuffle=True
            )

        # Ensure y_train_sub and y_val are integers
        y_train_sub = y_train_sub.astype(int)
        y_val = y_val.astype(int)

        # Apply RGSS oversampling on training data
        X_train_aug, y_train_aug = self.rgss_oversample(
            X_train_emb, y_train_sub, residuals[:len(y_train_sub)]
        )

        # Ensure y_train_aug is integer
        y_train_aug = y_train_aug.astype(int)

        # Compute attention weights
        attention_weights = self.compute_attention(X_train_aug)

        # Create LightGBM dataset with sample weights
        train_data = lgb.Dataset(
            X_train_aug,
            label=y_train_aug,
            weight=attention_weights
        )

        val_data = lgb.Dataset(
            X_val_emb,
            label=y_val,
            reference=train_data
        )

        # Calculate class weights for imbalance
        class_weights = class_weight.compute_class_weight(
            'balanced',
            classes=np.unique(y_train_aug),
            y=y_train_aug
        )
        class_weight_dict = dict(zip(np.unique(y_train_aug), class_weights))

        # Parameters for LightGBM - more conservative for reliability
        params = {
            'objective': 'binary',
            'metric': ['binary_logloss', 'auc'],
            'boosting_type': 'gbdt',
            'num_leaves': min(31, 2 ** self.max_depth),
            'learning_rate': self.learning_rate,
            'feature_fraction': 0.8,
            'bagging_fraction': 0.8,
            'bagging_freq': 5,
            'verbose': -1,
            'random_state': 42,
            'is_unbalance': False,
            'scale_pos_weight': class_weight_dict.get(1, 1.0) / class_weight_dict.get(0, 1.0),
            'min_child_samples': 20,
            'min_child_weight': 0.001,
            'reg_alpha': 0.1,
            'reg_lambda': 0.1,
            'max_depth': self.max_depth
        }

        # Train the model with early stopping
        self.model = lgb.train(
            params,
            train_data,
            valid_sets=[train_data, val_data],
            num_boost_round=self.n_estimators,
            callbacks=[
                lgb.early_stopping(self.early_stopping_rounds),
                lgb.log_evaluation(0)
            ]
        )

        # Store feature importance
        self.feature_importance = pd.DataFrame({
            'feature': range(X.shape[1]),
            'importance': self.model.feature_importance()
        }).sort_values('importance', ascending=False)

        self.fitted = True
        return self

    # Predict method
    def predict(self, X):
        if not self.fitted:
            raise ValueError("Model must be fitted before prediction")

        X_emb = self.rm_layer.transform(X)
        y_pred_prob = self.model.predict(X_emb, num_iteration=self.model.best_iteration)
        y_pred = (y_pred_prob >= 0.5).astype(int)
        return y_pred

    def predict_proba(self, X):
        if not self.fitted:
            raise ValueError("Model must be fitted before prediction")

        X_emb = self.rm_layer.transform(X)
        y_pred_prob = self.model.predict(X_emb, num_iteration=self.model.best_iteration)
        return np.column_stack([1 - y_pred_prob, y_pred_prob])

