def robustness_curve_no_retrain(model, X_test, y_test, noise_levels):

    acc_curve = []

    # Baseline
    y_pred = model.predict(X_test)
    baseline_acc = accuracy_score(y_test, y_pred)

    # Noise injection
    for noise in noise_levels:
        noise_matrix = np.random.normal(0, noise, X_test.shape)
        X_noisy = X_test + noise_matrix

        y_pred_noisy = model.predict(X_noisy)
        acc = accuracy_score(y_test, y_pred_noisy)

        acc_curve.append(acc)

    return baseline_acc, acc_curve

