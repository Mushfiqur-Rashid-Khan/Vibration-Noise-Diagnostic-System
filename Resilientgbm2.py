# -----------------------------
# Adaptive Threshold
# -----------------------------
def optimize_threshold(y_true, y_prob):
    best_t, best_f1 = 0.5, 0
    for t in np.linspace(0.2, 0.8, 30):
        y_pred = (y_prob >= t).astype(int)
        f1 = f1_score(y_true, y_pred, zero_division=0)
        if f1 > best_f1:
            best_f1 = f1
            best_t = t
    return best_t

# -----------------------------
# Spearman Selector
# -----------------------------
class SpearmanFeatureSelector:
    def __init__(self, threshold=0.08):
        self.threshold = threshold

    def fit(self, X, y):
        scores = []
        for i in range(X.shape[1]):
            corr, _ = spearmanr(X[:, i], y)
            scores.append(abs(corr) if not np.isnan(corr) else 0)

        self.idx = np.where(np.array(scores) > self.threshold)[0]
        if len(self.idx) == 0:
            self.idx = np.arange(X.shape[1])

    def transform(self, X):
        return X[:, self.idx]

# -----------------------------
# RMEL
# -----------------------------
class RMEL:
    def __init__(self, dim):
        self.mlp = MLPRegressor(hidden_layer_sizes=(32,), max_iter=150)

    def fit(self, X, r):
        self.mlp.fit(X, r)
        return self.transform(X, r)

    def transform(self, X, r):
        emb = self.mlp.predict(X).reshape(-1,1)
        return X + emb + 0.1*r.reshape(-1,1)

# -----------------------------
# Multi-task Model
# -----------------------------
class MultiTaskResGBM:

    def __init__(self):
        self.models = []
        self.thresholds = []

    def fit(self, X, Y):

        self.selector = SpearmanFeatureSelector()
        self.selector.fit(X, Y[:,0])

        X = self.selector.transform(X)

        residuals = np.linalg.norm(X - np.mean(X, axis=0), axis=1)

        self.rmel = RMEL(X.shape[1])
        X = self.rmel.fit(X, residuals)

        self.models = []
        self.thresholds = []

        for i in range(Y.shape[1]):
            y = Y[:, i]

            train_data = lgb.Dataset(X, y)

            model = lgb.train(
                {
                    'objective': 'binary',
                    'boosting_type': 'dart',
                    'learning_rate': 0.03,
                    'num_leaves': 50,
                    'max_depth': 7,
                    'class_weight': 'balanced',
                    'verbose': -1
                },
                train_data,
                num_boost_round=200
            )

            prob = model.predict(X)
            best_t = optimize_threshold(y, prob)

            self.models.append(model)
            self.thresholds.append(best_t)

    def predict_proba(self, X):
        X = self.selector.transform(X)
        X = self.rmel.transform(X, np.zeros(len(X)))

        probs = []
        for model in self.models:
            probs.append(model.predict(X))

        return np.array(probs).T

    def predict(self, X):
        probs = self.predict_proba(X)

        preds = []
        for i in range(probs.shape[1]):
            pred = (probs[:, i] >= self.thresholds[i]).astype(int)
            preds.append(pred)

        return np.array(preds).T


