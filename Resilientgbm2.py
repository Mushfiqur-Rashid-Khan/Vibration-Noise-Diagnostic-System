# -----------------------------
# RGSS Oversampling
# -----------------------------
def rgss_oversample(X, y, residuals, minority_class=1, ratio=0.4):
    idx = np.where(y == minority_class)[0]

    if len(idx) < 5:
        return X, y

    hard_idx = idx[np.argsort(residuals[idx])[-int(len(idx)*ratio):]]

    synth_X, synth_y = [], []

    for i in hard_idx:
        j = np.random.choice(idx)
        lam = np.random.rand()
        x_new = X[i] + lam * (X[j] - X[i])

        synth_X.append(x_new)
        synth_y.append(minority_class)

    if len(synth_X) > 0:
        X = np.vstack([X, np.array(synth_X)])
        y = np.hstack([y, np.array(synth_y)])

    return X, y

# -----------------------------
# Spearman Feature Selection
# -----------------------------
class SpearmanFeatureSelector:
    def __init__(self, threshold=0.08):
        self.threshold = threshold

    def fit(self, X, y):
        scores = []
        for i in range(X.shape[1]):
            corr, _ = spearmanr(X[:, i], y)
            scores.append(abs(corr) if not np.isnan(corr) else 0)

        self.selected_idx = np.where(np.array(scores) > self.threshold)[0]

        if len(self.selected_idx) == 0:
            self.selected_idx = np.arange(X.shape[1])

    def transform(self, X):
        return X[:, self.selected_idx]

    def fit_transform(self, X, y):
        self.fit(X, y)
        return self.transform(X)

# -----------------------------
# RMEL Layer
# -----------------------------
class RMEL:
    def __init__(self, input_dim, hidden_dim=32):
        self.mlp = MLPRegressor(hidden_layer_sizes=(hidden_dim,), max_iter=150, random_state=42)

    def compute_attention(self, X):
        alpha = np.mean(np.abs(X), axis=1)
        alpha = alpha / (np.max(alpha) + 1e-8)
        return alpha.reshape(-1, 1)

    def gradient_filter(self, residuals, tau=0.5):
        return residuals * (1 / (1 + np.exp(-residuals / tau)))

    def fit(self, X, residuals):
        residuals = self.gradient_filter(residuals)
        alpha = self.compute_attention(X)
        X_weighted = X * alpha

        self.mlp.fit(X_weighted, residuals)
        return self.transform(X, residuals)

    def transform(self, X, residuals):
        residuals = self.gradient_filter(residuals)
        alpha = self.compute_attention(X)
        X_weighted = X * alpha

        emb = self.mlp.predict(X_weighted).reshape(-1, 1)
        return X_weighted + emb + 0.1 * residuals.reshape(-1, 1)

# -----------------------------
# Model
# -----------------------------
class ResilientGBMPlusPlus:
    def __init__(self):
        self.model = None
        self.rm_layer = None
        self.selector = None

    def compute_residuals(self, X, y):
        residuals = np.zeros(len(y))
        for c in np.unique(y):
            idx = np.where(y == c)[0]
            class_mean = np.mean(X[idx], axis=0)
            residuals[idx] = np.linalg.norm(X[idx] - class_mean, axis=1)
        return residuals

    def fit(self, X, y):
        self.selector = SpearmanFeatureSelector()
        X = self.selector.fit_transform(X, y)

        residuals = self.compute_residuals(X, y)

        self.rm_layer = RMEL(input_dim=X.shape[1])
        X_emb = self.rm_layer.fit(X, residuals)

        X_train, X_val, y_train, y_val, r_train, r_val = train_test_split(
            X_emb, y, residuals, test_size=0.1, stratify=y, random_state=42
        )

        # RGSS
        X_train, y_train = rgss_oversample(X_train, y_train, r_train)

        lgb_train = lgb.Dataset(X_train, y_train)
        lgb_val = lgb.Dataset(X_val, y_val)

        params = {
            'objective': 'binary',
            'boosting_type': 'dart',
            'learning_rate': 0.03,
            'max_depth': 7,
            'num_leaves': 50,
            'feature_fraction': 0.8,
            'bagging_fraction': 0.8,
            'bagging_freq': 5,
            'reg_lambda': 1.5,
            'reg_alpha': 0.7,
            'class_weight': 'balanced',
            'metric': 'binary_logloss',
            'verbose': -1
        }

        self.model = lgb.train(
            params,
            lgb_train,
            num_boost_round=300,
            valid_sets=[lgb_val],
            callbacks=[lgb.early_stopping(30), lgb.log_evaluation(0)]
        )

    def predict(self, X):
        X = self.selector.transform(X)
        X_emb = self.rm_layer.transform(X, np.zeros(X.shape[0]))
        y_pred = self.model.predict(X_emb, num_iteration=self.model.best_iteration)
        return (y_pred >= 0.5).astype(int)

