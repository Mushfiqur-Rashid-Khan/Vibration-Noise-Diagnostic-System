# -----------------------------
# Residual Memory Embedding Layer (RMEL)
# -----------------------------
class RMEL:
    def __init__(self, input_dim, hidden_dim=32):
        self.mlp = MLPRegressor(hidden_layer_sizes=(hidden_dim,), max_iter=150, random_state=42)

    def fit(self, X, residuals):
        self.mlp.fit(X, residuals)
        return self.transform(X, residuals)

    def transform(self, X, residuals):
        emb = self.mlp.predict(X).reshape(-1, 1)
        Z = X + emb + 0.05 * residuals.reshape(-1, 1)
        return Z


# -----------------------------
# ResilientGBM++ (RGSS ratio now configurable)
# -----------------------------
class ResilientGBMPlusPlus:
    def __init__(self, n_estimators=150, learning_rate=0.05,
                 max_depth=6, minority_class=1, rgss_ratio=0.2):

        self.n_estimators = n_estimators
        self.learning_rate = learning_rate
        self.max_depth = max_depth
        self.minority_class = minority_class
        self.rgss_ratio = rgss_ratio

        self.model = None
        self.rm_layer = None

    def rgss_oversample(self, X, y, residuals):
        idx = np.where(y == self.minority_class)[0]
        if len(idx) == 0:
            return X, y

        k = max(1, int(self.rgss_ratio * len(idx)))
        top_idx = idx[np.argsort(np.abs(residuals[idx]))[-k:]]

        synth_samples, synth_labels = [], []

        for i in top_idx:
            j = np.random.choice(idx)
            lam = np.random.rand()
            x_new = X[i] + lam * (X[j] - X[i])
            synth_samples.append(x_new)
            synth_labels.append(self.minority_class)

        X_aug = np.vstack([X, np.array(synth_samples)])
        y_aug = np.hstack([y, np.array(synth_labels)])

        return X_aug, y_aug

    def fit(self, X, y):
        residuals = np.zeros(X.shape[0])

        self.rm_layer = RMEL(input_dim=X.shape[1])
        X_emb = self.rm_layer.fit(X, residuals)

        X_train, X_val, y_train, y_val = train_test_split(
            X_emb, y, test_size=0.1, random_state=42, stratify=y
        )

        X_train_aug, y_train_aug = self.rgss_oversample(
            X_train, y_train, residuals[:len(y_train)]
        )

        lgb_train = lgb.Dataset(X_train_aug, y_train_aug)
        lgb_val = lgb.Dataset(X_val, y_val, reference=lgb_train)

        params = {
            'objective': 'multiclass' if len(np.unique(y)) > 2 else 'binary',
            'num_class': len(np.unique(y)) if len(np.unique(y)) > 2 else 1,
            'learning_rate': self.learning_rate,
            'max_depth': self.max_depth,
            'num_leaves': 31,
            'reg_lambda': 1.0,
            'reg_alpha': 0.5,
            'class_weight': 'balanced',
            'metric': 'multi_logloss' if len(np.unique(y)) > 2 else 'binary_logloss',
            'verbose': -1
        }

        self.model = lgb.train(
            params,
            lgb_train,
            num_boost_round=self.n_estimators,
            valid_sets=[lgb_train, lgb_val],
            valid_names=['train', 'val'],
            callbacks=[lgb.early_stopping(20), lgb.log_evaluation(0)]
        )

    def predict(self, X):
        X_emb = self.rm_layer.transform(X, np.zeros(X.shape[0]))
        y_pred = self.model.predict(X_emb, num_iteration=self.model.best_iteration)

        if len(y_pred.shape) == 1:
            return (y_pred >= 0.5).astype(int)
        else:
            return np.argmax(y_pred, axis=1)


