def plot_top_spearman_correlated_features(df, top_n=20, figsize=(12, 10)):

    # -----------------------------
    # SPEARMAN CORRELATION MATRIX
    # -----------------------------
    corr_matrix = df.corr(method='spearman').abs()

    # Upper triangle (avoid duplicates)
    mask = np.triu(np.ones_like(corr_matrix, dtype=bool), k=1)

    upper_tri = corr_matrix.where(mask).stack().reset_index()
    upper_tri.columns = ['feature1', 'feature2', 'correlation']

    # Strongest correlations
    top_correlations = upper_tri.sort_values('correlation', ascending=False).head(top_n * 2)

    # Unique features
    unique_features = pd.unique(top_correlations[['feature1', 'feature2']].values.ravel())

    # Rank features by average correlation
    if len(unique_features) > top_n:
        feature_avg_corr = []

        for feature in unique_features:
            feature_corrs = corr_matrix[feature].drop(feature, errors='ignore')
            avg_corr = feature_corrs.mean()
            feature_avg_corr.append((feature, avg_corr))

        feature_avg_corr.sort(key=lambda x: x[1], reverse=True)
        selected_features = [f[0] for f in feature_avg_corr[:top_n]]
    else:
        selected_features = list(unique_features)

    # Sub-correlation matrix
    sub_corr = corr_matrix.loc[selected_features, selected_features]

    # -----------------------------
    # PLOT (Q1 READY)
    # -----------------------------
    plt.figure(figsize=figsize, dpi=300)

    ax = sns.heatmap(
        sub_corr,
        annot=True,
        fmt=".2f",
        cmap="RdBu_r",
        center=0,
        vmin=0, vmax=1,
        square=True,
        linewidths=0.5,
        cbar_kws={
            "shrink": 0.8,
            "label": "Spearman Correlation"
        },
        annot_kws={"size": 8, "weight": "bold"}
    )

    # -----------------------------
    # IMPROVE TEXT READABILITY
    # -----------------------------
    for text in ax.texts:
        value = float(text.get_text())
        if value > 0.6:
            text.set_color("white")
        else:
            text.set_color("black")

    # -----------------------------
    # TITLE + AXES
    # -----------------------------
    plt.title(
        f"Spearman Correlation Heatmap (Top {len(selected_features)} Features)",
        fontsize=14,
        fontweight='bold'
    )

    plt.xticks(rotation=45, ha='right', fontsize=10, fontweight='bold')
    plt.yticks(rotation=0, fontsize=10, fontweight='bold')

    plt.tight_layout()
    plt.show()

    return sub_corr, selected_features


