from PIL import Image, ImageEnhance

# ---------------------------------------------------
# LOAD IMAGES
# ---------------------------------------------------
image_files = [
    "signal drift.png",
    "gas leakage.png",
    "high noise level.png",
    "radiation.png",
    "thermal drift.png",
    "sensor aging.png",
    "offset bias.png",
    "wiring reversal.png"
]

images = [Image.open(img).convert("RGB") for img in image_files]

# ---------------------------------------------------
# SETTINGS (HIGH QUALITY)
# ---------------------------------------------------
cols = 3
rows = 3

target_width = 600   # higher = better clarity
target_height = 400

padding = 40  # spacing between images

# ---------------------------------------------------
# RESIZE (KEEP ASPECT RATIO)
# ---------------------------------------------------
resized_images = []

for img in images:
    img.thumbnail((target_width, target_height), Image.LANCZOS)

    # Create white background
    canvas = Image.new("RGB", (target_width, target_height), (255, 255, 255))

    # Center image
    x = (target_width - img.width) // 2
    y = (target_height - img.height) // 2
    canvas.paste(img, (x, y))

    # Optional sharpening
    enhancer = ImageEnhance.Sharpness(canvas)
    canvas = enhancer.enhance(1.5)

    resized_images.append(canvas)

# ---------------------------------------------------
# CREATE LARGE CANVAS
# ---------------------------------------------------
total_width = cols * target_width + (cols - 1) * padding
total_height = rows * target_height + (rows - 1) * padding

combined = Image.new("RGB", (total_width, total_height), (255, 255, 255))

# ---------------------------------------------------
# PASTE IMAGES
# ---------------------------------------------------
for i, img in enumerate(resized_images):
    x = (i % cols) * (target_width + padding)
    y = (i // cols) * (target_height + padding)
    combined.paste(img, (x, y))

# ---------------------------------------------------
# SAVE HIGH-QUALITY OUTPUT
# ---------------------------------------------------
combined.save(
    "combined_high_quality.png",
    dpi=(300, 300),        # 🔥 journal standard
    quality=95,
    subsampling=0
)

combined.show()

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.preprocessing import StandardScaler

# -----------------------------
# LOAD DATA (SAFE CHECK)
# -----------------------------
if 'df_vib' not in globals():
    df_vib = pd.read_csv('Vibration_Dataset.csv', encoding='ascii')

# -----------------------------
# STYLE (Q1 JOURNAL STANDARD)
# -----------------------------
plt.rcParams.update({
    "font.family": "serif",
    "font.size": 12,
    "font.weight": "bold",
    "axes.labelweight": "bold",
    "axes.titleweight": "bold"
})

# -----------------------------
# DETECT LABEL COLUMNS
# -----------------------------
label_cols = []

for col_nm in df_vib.columns:
    if col_nm in ['Temperature', 'Pressure']:
        continue

    if df_vib[col_nm].nunique(dropna=False) == 2:
        vals = set(pd.Series(df_vib[col_nm].dropna().unique()).tolist())
        if vals.issubset({0, 1, 0.0, 1.0}):
            label_cols.append(col_nm)

# -----------------------------
# FEATURE PREPROCESSING
# -----------------------------
num_cols = df_vib.select_dtypes(include=[np.number]).columns.tolist()
feature_cols = [c for c in num_cols if c not in label_cols]

X = df_vib[feature_cols].copy()

# Remove zero-variance features
feat_var = X.var(numeric_only=True)
X = X.loc[:, feat_var[feat_var > 0].index]

X_scaled = StandardScaler().fit_transform(X.values)

# -----------------------------
# UMAP COMPUTATION
# -----------------------------
if 'emb_df_umap' not in globals():
    import umap

    umap_model = umap.UMAP(
        n_neighbors=30,
        min_dist=0.05,
        metric='cosine',
        random_state=42
    )

    emb_umap = umap_model.fit_transform(X_scaled)
    emb_df_umap = pd.DataFrame({
        'UMAP1': emb_umap[:, 0],
        'UMAP2': emb_umap[:, 1]
    })

# -----------------------------
# SORT LABELS (MOST FREQUENT FIRST)
# -----------------------------
label_counts = df_vib[label_cols].sum().sort_values(ascending=False)

cols = 4
rows = int(np.ceil(len(label_counts) / cols))

plt.figure(figsize=(4.5 * cols, 3.8 * rows), dpi=300)

# -----------------------------
# PLOTTING EACH FAULT
# -----------------------------
for i, lab in enumerate(label_counts.index.tolist()):
    ax = plt.subplot(rows, cols, i + 1)

    y = df_vib[lab].values
    idx0 = (y == 0)
    idx1 = (y == 1)

    # Background (no fault)
    ax.scatter(
        emb_df_umap.loc[idx0, 'UMAP1'],
        emb_df_umap.loc[idx0, 'UMAP2'],
        s=10,
        c='#9CA3AF',
        alpha=0.35,
        linewidths=0
    )

    # Fault points (strong red emphasis)
    ax.scatter(
        emb_df_umap.loc[idx1, 'UMAP1'],
        emb_df_umap.loc[idx1, 'UMAP2'],
        s=16,
        c='#DC2626',
        alpha=0.9,
        edgecolors='black',
        linewidths=0.2
    )

    ax.set_title(
        f"{lab} (n={int(label_counts[lab])})",
        fontsize=11,
        fontweight='bold'
    )

    ax.set_xticks([])
    ax.set_yticks([])

    # Clean but visible frame
    for spine in ax.spines.values():
        spine.set_linewidth(1.0)

# -----------------------------
# TURN OFF UNUSED SUBPLOTS
# -----------------------------
n_total = rows * cols
n_used = len(label_counts)

for j in range(n_used + 1, n_total + 1):
    ax_unused = plt.subplot(rows, cols, j)
    ax_unused.axis('off')

# -----------------------------
# GLOBAL TITLE
# -----------------------------
plt.suptitle(
    "UMAP 2D Embedding: Fault-wise Visualization",
    fontsize=16,
    fontweight='bold',
    y=1.02
)

plt.tight_layout()


plt.show()

