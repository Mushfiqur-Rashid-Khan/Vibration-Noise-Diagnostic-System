# ==========================================================
# 🔥 MODEL
# ==========================================================
class ResilientGBMPlusPlus:
    def __init__(self):
        self.selector = None
        self.rmel = None
        self.model = None

    def compute_residuals(self, X):
        return np.linalg.norm(X - np.mean(X, axis=0), axis=1)

    def fit(self, X, y):

        self.selector = SpearmanFeatureSelector()
        X = self.selector.fit_transform(X, y)

        residuals = self.compute_residuals(X)

        self.rmel = RMEL(X.shape[1])
        X = self.rmel.fit(X, residuals)

        train_data = lgb.Dataset(X, y)

        self.model = lgb.train(
            {
                'objective': 'binary',
                'boosting_type': 'dart',
                'learning_rate': 0.03,
                'num_leaves': 50,
                'max_depth': 7,
                'class_weight': 'balanced',
                'verbose': -1
            },
            train_data,
            num_boost_round=200
        )

    def predict(self, X):
        X = self.selector.transform(X)
        X = self.rmel.transform(X, np.zeros(len(X)))
        prob = self.model.predict(X)
        return (prob >= 0.5).astype(int)

# ==========================================================
# 🔥 ROBUSTNESS FUNCTION (NO RETRAINING)
# ==========================================================
def robustness_curve_no_retrain(model, X_test, y_test, noise_levels):

    acc_curve = []

    # Baseline
    y_pred = model.predict(X_test)
    baseline_acc = accuracy_score(y_test, y_pred)

    # Noise injection
    for noise in noise_levels:
        noise_matrix = np.random.normal(0, noise, X_test.shape)
        X_noisy = X_test + noise_matrix

        y_pred_noisy = model.predict(X_noisy)
        acc = accuracy_score(y_test, y_pred_noisy)

        acc_curve.append(acc)

    return baseline_acc, acc_curve

