# -----------------------------
# ResilientGBM++
# -----------------------------
class ResilientGBMPlusPlus:
    def __init__(self, rgss_ratio=0.2):

        self.rgss_ratio = rgss_ratio
        self.model = None
        self.rm_layer = None

    def rgss_oversample(self, X, y, residuals):
        idx = np.where(y == 1)[0]
        if len(idx) == 0:
            return X, y

        k = max(1, int(self.rgss_ratio * len(idx)))
        top_idx = idx[np.argsort(np.abs(residuals[idx]))[-k:]]

        synth_x, synth_y = [], []

        for i in top_idx:
            j = np.random.choice(idx)
            lam = np.random.rand()
            synth_x.append(X[i] + lam * (X[j] - X[i]))
            synth_y.append(1)

        return np.vstack([X, synth_x]), np.hstack([y, synth_y])

    def fit(self, X, y):

        residuals = np.zeros(X.shape[0])

        self.rm_layer = RMEL(X.shape[1])
        X = self.rm_layer.fit(X, residuals)

        X, y = self.rgss_oversample(X, y, residuals)

        train_data = lgb.Dataset(X, y)

        self.model = lgb.train(
            {
                'objective': 'binary',
                'learning_rate': 0.05,
                'max_depth': 6,
                'num_leaves': 31,
                'verbose': -1
            },
            train_data,
            num_boost_round=150
        )

    def predict(self, X):
        X = self.rm_layer.transform(X, np.zeros(X.shape[0]))
        prob = self.model.predict(X)
        return (prob >= 0.5).astype(int)


