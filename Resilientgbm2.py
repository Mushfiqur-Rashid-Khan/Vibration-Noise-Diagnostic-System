def describe_correlation_matrix(df, method='spearman', threshold=0.7):
    """
    Descriptive analysis of correlation matrix for research papers.
    """

    # -----------------------------
    # CORRELATION MATRIX
    # -----------------------------
    corr = df.corr(method=method)

    print("\n==============================")
    print(f"{method.upper()} CORRELATION MATRIX SUMMARY")
    print("==============================\n")

    # -----------------------------
    # BASIC STATISTICS
    # -----------------------------
    corr_values = corr.values.flatten()
    corr_values = corr_values[corr_values != 1]  # remove diagonal

    print(f"Mean Correlation: {np.mean(corr_values):.4f}")
    print(f"Std Deviation   : {np.std(corr_values):.4f}")
    print(f"Max Correlation  : {np.max(corr_values):.4f}")
    print(f"Min Correlation  : {np.min(corr_values):.4f}")

    # -----------------------------
    # STRONG POSITIVE CORRELATIONS
    # -----------------------------
    upper = corr.where(np.triu(np.ones(corr.shape), k=1).astype(bool))

    strong_pos = (
        upper.stack()
        .reset_index()
        .rename(columns={'level_0': 'Feature1',
                         'level_1': 'Feature2',
                         0: 'Correlation'})
    )

    strong_pos = strong_pos.sort_values(by='Correlation', ascending=False)

    print("\nTop 10 Positive Correlations:")
    print(strong_pos.head(10))

    # -----------------------------
    # STRONG NEGATIVE CORRELATIONS
    # -----------------------------
    strong_neg = strong_pos.sort_values(by='Correlation', ascending=True)

    print("\nTop 10 Negative Correlations:")
    print(strong_neg.head(10))

    # -----------------------------
    # HIGHLY CORRELATED PAIRS
    # -----------------------------
    high_corr = strong_pos[strong_pos['Correlation'] >= threshold]

    print(f"\nHighly Correlated Pairs (|r| ≥ {threshold}):")
    print(high_corr)

    print(f"\nTotal Highly Correlated Pairs: {len(high_corr)}")

    # -----------------------------
    # FEATURE REDUNDANCY INSIGHT
    # -----------------------------
    feature_counts = {}

    for _, row in high_corr.iterrows():
        f1, f2 = row['Feature1'], row['Feature2']
        feature_counts[f1] = feature_counts.get(f1, 0) + 1
        feature_counts[f2] = feature_counts.get(f2, 0) + 1

    redundancy_df = pd.DataFrame(
        sorted(feature_counts.items(), key=lambda x: x[1], reverse=True),
        columns=["Feature", "High-Corr Connections"]
    )

    print("\nMost Redundant Features (Top Connected):")
    print(redundancy_df.head(10))

    return corr, strong_pos, high_corr, redundancy_df


